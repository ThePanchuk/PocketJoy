/**
 * Translations for everything people see.
 *
 * English is the default and the fallback: a missing key falls back to the
 * English text rather than showing the key itself, so a half-finished
 * translation still gives a usable screen.
 *
 * The language is picked automatically from the browser, and whoever wants
 * something else can choose it - on the phone in the menu, in the lobby at
 * the top. The choice is remembered per device.
 *
 * Adding a language: put its code in LANGUAGES and its texts in STRINGS.
 * Anything not translated simply stays English.
 *
 * Right-to-left languages (Arabic, Hebrew) are deliberately absent - they
 * need mirrored layouts, and a half-done job there is worse than none.
 */

