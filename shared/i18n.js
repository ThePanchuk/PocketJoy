const STORAGE_KEY = 'pocketjoy.lang';
let current = DEFAULT_LANGUAGE;
const listeners = new Set();

function known(code) {
  return LANGUAGES.some((l) => l.code === code) ? code : null;
}

/** Browser preference first, then English. "de-AT" counts as "de". */
export function detectLanguage() {
  try {
    const stored = localStorage.getItem(STORAGE_KEY);
    if (known(stored)) return stored;
  } catch { /* storage blocked */ }

  const wanted = globalThis.navigator?.languages?.length
    ? globalThis.navigator.languages
    : [globalThis.navigator?.language].filter(Boolean);

  for (const tag of wanted) {
    const base = known(String(tag).toLowerCase().split('-')[0]);
    if (base) return base;
  }
  return DEFAULT_LANGUAGE;
}

export function getLanguage() { return current; }

export function setLanguage(code, { remember = true } = {}) {
  const next = known(code) || DEFAULT_LANGUAGE;
  current = next;
  if (remember) {
    try { localStorage.setItem(STORAGE_KEY, next); } catch { /* storage blocked */ }
  }
  if (globalThis.document) globalThis.document.documentElement.lang = next;
  for (const cb of listeners) {
    try { cb(next); } catch (err) { console.error('[pocketjoy]', err); }
  }
  return next;
}

/** Called whenever the language changes, so a page can redraw its texts. */
export function onLanguageChange(cb) {
  listeners.add(cb);
  return () => listeners.delete(cb);
}

/**
 * Look up a text. Unknown keys fall back to English, then to the key itself -
 * a missing translation should never leave an empty screen.
 */
export function t(key, vars) {
  const text = STRINGS[current]?.[key] ?? STRINGS[DEFAULT_LANGUAGE][key] ?? key;
  if (!vars) return text;
  return text.replace(/\{(\w+)\}/g, (whole, name) => (
    vars[name] !== undefined ? String(vars[name]) : whole
  ));
}

/** Translate the name/hint of a layout; a game's own layout keeps its text. */
export function layoutText(layout, field = 'name') {
  if (!layout) return '';
  if (layout.custom) {
    return field === 'name'
      ? (layout.name || t('layout.custom'))
      : (layout.hint || t('layout.custom.hint'));
  }
  const key = `layout.${layout.id}.${field}`;
  const translated = STRINGS[current]?.[key] ?? STRINGS[DEFAULT_LANGUAGE][key];
  return translated ?? layout[field] ?? '';
}

/** Apply once at start-up. */
setLanguage(detectLanguage(), { remember: false });
